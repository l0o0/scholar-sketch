// Fonts for the film (generated, not committed; build.mjs runs this when the output is missing).
// - "PingFang SC": the container has no PingFang SC / Microsoft YaHei, so CJK text in the product UI
//   would fall back to WenQuanYi Zen Hei (one weight, synthetic bold). The product's font stacks
//   (src/ui/theme.ts, src/editor/theme.ts, whiteboard app.tsx) all list "PingFang SC", so Noto Sans SC
//   (SIL OFL 1.1, @fontsource/noto-sans-sc) is registered under that name. Product CSS is untouched.
// - "Film Sans SC": the same files under the film's own family for title cards, with more weights.
// Output: public/fonts/*.woff2 + src/fonts.generated.css (also injected into iframe pages by build.mjs).
// Usage: node tools/gen-cjk-font.mjs
import {readFile, writeFile, mkdir, copyFile} from 'node:fs/promises';
const pkg = 'node_modules/@fontsource/noto-sans-sc';
const FAMILIES = {'PingFang SC': [400, 700], 'Film Sans SC': [300, 400, 500, 700, 900]};
await mkdir('public/fonts', {recursive: true});
let css = '/* generated by tools/gen-cjk-font.mjs — Noto Sans SC (SIL OFL 1.1) */\n';
const copied = new Set();
for (const [family, weights] of Object.entries(FAMILIES)) {
  for (const w of weights) {
    const src = await readFile(`${pkg}/${w}.css`, 'utf8');
    for (const block of src.split('@font-face').slice(1)) {
      const woff2 = block.match(/url\(\.\/files\/([^)]+\.woff2)\)/)[1];
      const range = block.match(/unicode-range:\s*([^;]+);/)[1];
      if (!copied.has(woff2)) { await copyFile(`${pkg}/files/${woff2}`, `public/fonts/${woff2}`); copied.add(woff2); }
      css += `@font-face{font-family:"${family}";font-style:normal;font-weight:${w};font-display:block;src:url(/fonts/${woff2}) format("woff2");unicode-range:${range};}\n`;
    }
  }
}
await writeFile('src/fonts.generated.css', css);
console.log(JSON.stringify({files: copied.size}));
